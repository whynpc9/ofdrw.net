#!/usr/bin/env python3
"""Regenerate src/Ofdrw.Net.Archival/ArchivalClauseMatrix.Data.cs from the reviewed matrix JSON.

ArchivalClauseMatrixTests fails when the generated table and the JSON differ. Bump
ArchivalClauseMatrix.Revision whenever a regenerated row changes.
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'docs/engineering/baselines/gbt42133-2022-clause-applicability.json'
TARGET = ROOT / 'src/Ofdrw.Net.Archival/ArchivalClauseMatrix.Data.cs'


def literal(value):
    if value is None:
        return 'null'
    return '"' + value.replace('\\', '\\\\').replace('"', '\\"') + '"'


def strings(values):
    return 'new string[] { ' + ', '.join(literal(v) for v in values) + ' }' if values else 'Array.Empty<string>()'


def main():
    data = json.loads(SOURCE.read_text(encoding='utf-8'))
    rows = []
    for item in data['items']:
        mixed = item.get('mixedStrengths')
        mixed_text = ('new[] { ' + ', '.join(
            f'new ArchivalMixedStrength(ArchivalClauseStrength.{m["strength"]}, {literal(m["part"])})' for m in mixed) + ' }'
            if mixed else 'Array.Empty<ArchivalMixedStrength>()')
        rows.append(
            f'        new ArchivalClauseMatrixEntry({literal(item["clause"])}, ArchivalClauseStrength.{item["strength"]}, '
            f'{literal(item["modalKeyword"])}, {mixed_text},\n'
            f'            {str(item["conditional"]).lower()}, {literal(item["condition"])}, {item["pdfPage"]}, '
            f'{literal(item["printedPage"])}, ArchivalMatrixConfidence.{item["confidence"]},\n'
            f'            ArchivalProfileApplicability.{item["firstProfile"]}, {strings(item["rules"])}, '
            f'{strings(item["referencedStandards"])}, {str(item["editionFixed"]).lower()}, {literal(item.get("note"))}),')
    body = '\n'.join(rows)
    TARGET.write_text(f'''// <auto-generated>
// Generated from docs/engineering/baselines/gbt42133-2022-clause-applicability.json.
// Do not edit by hand: ArchivalClauseMatrixTests fails when this table and the JSON differ.
// </auto-generated>
#nullable enable
using System;

namespace Ofdrw.Net.Archival;

public static partial class ArchivalClauseMatrix
{{
    private static ArchivalClauseMatrixEntry[] CreateEntries() => new[]
    {{
{body}
    }};
}}
''', encoding='utf-8')
    print(f'Wrote {len(rows)} rows to {TARGET.relative_to(ROOT)}.')


if __name__ == '__main__':
    main()
