    internal static bool RequiresBidiMirroring(int scalar)
    {
        var low = 0; var high = Ranges.Length / 2 - 1;
        while (low <= high)
        {
            var mid = low + (high - low) / 2;
            if (scalar < Ranges[mid * 2]) high = mid - 1;
            else if (scalar > Ranges[mid * 2 + 1]) low = mid + 1;
            else return true;
        }
        return false;
    }
